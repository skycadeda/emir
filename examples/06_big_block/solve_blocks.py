"""How fast SciPy's SuperLU back-substitutes several right-hand sides at once:
the measurement behind `SOLVE_BLOCK` and `CHUNK_MAX` in `emir/bigblock.py`.

    python solve_blocks.py --n 300 --csv results/solve_blocks.csv

Factorises the grid of a synthetic mesh (`mesh.stream_case`, the same as
stream_check.py) and times `lu.solve` on random right-hand sides in blocks of
1 to 64 columns (best of --repeat), with --threads BLAS threads (1, the
default, or `default`: the library's own choice). Then the whole streamed
superposition of that case with chunks of 8 to 512 samples, timed in this
process with `tracemalloc`'s peak for the chunk's arrays. SYNTHETIC; this
machine's times.
"""
from __future__ import annotations

import argparse
import csv
import os
import sys
import time

#: --threads N must take effect before numpy loads its BLAS
_THREADS = (sys.argv[sys.argv.index("--threads") + 1] if "--threads" in sys.argv else "1")
if _THREADS != "default":
    for _k in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
        os.environ[_k] = _THREADS

import numpy as np  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import mesh  # noqa: E402


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0], allow_abbrev=False)
    ap.add_argument("--n", type=int, default=300)
    ap.add_argument("--k", type=int, default=2000)
    ap.add_argument("--nt", type=int, default=501)
    ap.add_argument("--repeat", type=int, default=3)
    ap.add_argument("--threads", default="1",
                    help="BLAS threads: a number, or `default` (the library's choice)")
    ap.add_argument("--append", action="store_true", help="append to --csv")
    ap.add_argument("--out", default=os.path.join(HERE, "out", "blocks"))
    ap.add_argument("--csv", default=None)
    a = ap.parse_args(argv)
    import tracemalloc

    from emir import bigblock, ccsim
    from emir import dspf as D
    quiet = lambda *x, **y: None                              # noqa: E731
    case = mesh.stream_case(a.n, a.k, a.nt, a.out)
    d = D.parse(case["dspf"])
    nw = D.Network(d, "VDD")
    (_, _, fi, lu), = nw._factor("VDD")
    rng = np.random.default_rng(0)
    rows = []
    for c in (1, 2, 4, 8, 12, 16, 24, 32, 64):
        B = rng.standard_normal((len(fi), c))
        best = min(_timed(lambda: lu.solve(B)) for _ in range(a.repeat))
        rows.append({"what": "solve_block", "threads": a.threads, "size": c,
                     "ms_per_column": 1e3 * best / c})
    ing = ccsim.cc_taps(d, "VDD", case["raw"], feed="VDD", log=quiet)
    keep = bigblock.CHUNK_MAX
    try:
        for c in (8, 16, 32, 64, 128, 512):
            bigblock.CHUNK_MAX = c
            tracemalloc.start()
            t = _timed(lambda: bigblock.superpose_stream(
                nw, "VDD", ing["taps"], ("avg", "rms", "peak"), weights=ing["weights"],
                max_bytes=64 << 30, log=quiet))
            peak = tracemalloc.get_traced_memory()[1]
            tracemalloc.stop()
            rows.append({"what": "stream_chunk", "threads": a.threads, "size": c,
                         "seconds": t, "peak_traced_MB": peak / 2 ** 20})
    finally:
        bigblock.CHUNK_MAX = keep
    for r in rows:
        print(r)
    if a.csv:
        os.makedirs(os.path.dirname(os.path.abspath(a.csv)), exist_ok=True)
        new = not (a.append and os.path.exists(a.csv))
        with open(a.csv, "a" if a.append else "w", newline="", encoding="utf-8") as f:
            if new:
                f.write(f"# {case['tag']}: {case['nodes']} nodes, {case['resistors']} "
                        f"resistors, {case['taps']} taps, {case['points']} points; "
                        f"synthetic, SciPy SuperLU, a shared machine. Generated by "
                        f"solve_blocks.py\n")
            w = csv.DictWriter(f, fieldnames=["what", "threads", "size", "ms_per_column",
                                              "seconds", "peak_traced_MB"])
            if new:
                w.writeheader()
            for r in rows:
                w.writerow({k: (f"{v:.4g}" if isinstance(v, float) else v)
                            for k, v in r.items()})
    return 0


def _timed(fn) -> float:
    t0 = time.perf_counter()
    fn()
    return time.perf_counter() - t0


if __name__ == "__main__":
    raise SystemExit(main())
