#!/usr/bin/env python3
"""Write docs/cli-reference.md, the command-line reference, from the commands'
own argparse parsers. The parsers are the single source; never edit the page
by hand.

    python scripts/gen_cli_reference.py            # write it
    python scripts/gen_cli_reference.py --check    # exit 1 if it is stale

`tests/test_docs.py` runs the check. The page is built from the parsers'
actions, not from `format_help()`, so it does not depend on the terminal width
or on the Python version's help layout.
"""
from __future__ import annotations

import argparse
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "docs", "cli-reference.md")

HEADER = """\
# Command-line reference

<!-- GENERATED by scripts/gen_cli_reference.py from the commands' own parsers.
     Do not edit by hand: change the parser, then run the script. -->

Every `emir` command, with every option, as its parser defines it. This page is
generated from the code (`python scripts/gen_cli_reference.py`), and a test fails
when it is stale, so it cannot drift from what the commands accept.

Conventions shared by every command (see [Concepts](concepts.md) and the agent
contract in [`agent/CONTRACT.md`](../agent/CONTRACT.md)):

- `--format json` prints exactly one JSON document on stdout (its `schema` field
  names it; `emir schema <name>` prints the JSON Schema). Logs go to stderr.
- Exit status: 0 done; 1 with `--fail-on-violation`, a FAIL verdict (an IR budget
  FAIL, or an EM basis asked for and not computed: `em_basis.honoured` false); 2 bad input
  or refused (`emir check`: inputs not OK); 3 a required tool or package is
  missing; 70 internal error or a failed self-test or validation; 130
  interrupted (SIGINT); 143 terminated (SIGTERM).
- Option abbreviations are refused: write every option in full. `@FILE`
  arguments are read from FILE, one argument per line.
- Every failure carries a code `EMIR-Exxx` (`emir explain <code>`; the catalog is
  [`agent/errors.md`](../agent/errors.md)).

Screening, not sign-off: every result these commands print screens the layout;
foundry-qualified EM/IR remains the sign-off flow. EMIR is a research project,
provided as is, with no warranty or guarantee of accuracy: test and verify its
results for your process, tools and design before relying on them.

"""

GROUP_TITLES = {"positional arguments": "Arguments", "options": "Options",
                "optional arguments": "Options"}


def _escape_text(s: str) -> str:
    """Markdown-safe text outside code spans: `<`, `>`, `*`, `|` and `_` at
    word edges would otherwise turn into HTML tags or emphasis."""
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("*", r"\*").replace("|", r"\|")
    return re.sub(r"(?<![\w\\])_|_(?!\w)", r"\_", s)


def escape(s: str) -> str:
    """Escape `s` for a Markdown paragraph or list item, keeping `code` spans
    (single backticks) as they are. RST-style ``double`` backticks become
    single ones."""
    s = s.replace("``", "`")
    parts = s.split("`")
    if len(parts) % 2 == 0:                     # an unpaired backtick: no code spans
        return _escape_text(s)
    return "".join(_escape_text(p) if i % 2 == 0 else f"`{p}`"
                   for i, p in enumerate(parts))


def expand_help(action, prog: str) -> str:
    """The action's help with argparse's `%(...)s` fields filled, as argparse
    does it. A BooleanOptionalAction's automatic "(default: ...)" suffix, which
    Python versions add differently, is dropped."""
    text = action.help or ""
    text = text.replace(" (default: %(default)s)", "")
    params = dict(vars(action), prog=prog)
    for k in list(params):
        if params[k] is argparse.SUPPRESS:
            del params[k]
    for k in list(params):
        if hasattr(params[k], "__name__"):
            params[k] = params[k].__name__
    if params.get("choices") is not None:
        params["choices"] = ", ".join(str(c) for c in params["choices"])
    try:
        text = text % params
    except (KeyError, TypeError, ValueError):
        pass
    return " ".join(text.split())


def metavar(action) -> str:
    """How the value is written: `{a,b}`, the metavar, or the dest in capitals."""
    if action.nargs == 0:
        return ""
    if action.metavar is not None:
        mv = action.metavar if isinstance(action.metavar, str) else " ".join(action.metavar)
    elif action.choices is not None:
        mv = "{" + ",".join(str(c) for c in action.choices) + "}"
    elif action.option_strings:
        mv = action.dest.upper()
    else:
        mv = action.dest
    n = action.nargs
    if n is None or n == 1:
        return mv
    if n == "?":
        return f"[{mv}]"
    if n == "*":
        return f"[{mv} ...]"
    if n == "+":
        return f"{mv} [{mv} ...]"
    if isinstance(n, int):
        return " ".join([mv] * n)
    return mv


def default_text(action) -> str:
    d = action.default
    if (action.nargs == 0 or d is None or d is argparse.SUPPRESS or d is False
            or d == [] or d == ""):
        return ""
    return str(d)


def synopsis(cmd: str, p) -> str:
    """`emir <cmd> POSITIONAL --required VALUE ... [options]`."""
    words = [f"emir {cmd}"]
    for a in p._actions:
        if a.help is argparse.SUPPRESS or isinstance(a, argparse._HelpAction):
            continue
        if not a.option_strings:
            words.append(metavar(a))
        elif a.required:
            mv = metavar(a)
            words.append(f"{a.option_strings[-1]} {mv}".strip())
    words.append("[options]")
    return " ".join(words)


def item(action, prog: str) -> str:
    """One option as a list item: the flags and value, its help, its default."""
    if action.option_strings:
        mv = metavar(action)
        flags = ", ".join(f"`{o}{(' ' + mv) if mv else ''}`" for o in action.option_strings)
        if isinstance(action, argparse.BooleanOptionalAction):
            flags = ", ".join(f"`{o}`" for o in action.option_strings)
    else:
        flags = f"`{metavar(action)}`"
    bits = []
    h = expand_help(action, prog)
    if h:
        bits.append(escape(h))
    tags = []
    if action.required and action.option_strings:
        tags.append("required")
    if isinstance(action, argparse._AppendAction) and "repeat" not in h:
        tags.append("repeatable")
    dflt = default_text(action)
    if dflt and "default" not in h.lower():     # the help already states it
        tags.append(f"default `{dflt}`")
    line = f"- {flags}"
    if bits:
        line += ": " + bits[0]
    if tags:
        line += f" ({'; '.join(tags)})"
    return line


def description(text: str) -> list:
    """The first paragraph as text, any further ones verbatim in a text block."""
    paras = [p for p in re.split(r"\n\s*\n", (text or "").strip()) if p.strip()]
    if not paras:
        return []
    out = [escape(" ".join(paras[0].split())), ""]
    if len(paras) > 1:
        out += ["```text", "\n\n".join(p.rstrip() for p in paras[1:]), "```", ""]
    return out


def summary_line(cmd: str, p) -> str:
    """The description's first sentence, for the table of commands."""
    first = re.split(r"\n\s*\n", (p.description or "").strip())[0]
    first = " ".join(first.split())
    first = re.sub(rf"^`emir {re.escape(cmd)}`:\s*", "", first)
    first = re.split(r"(?<=\.)\s", first, maxsplit=1)[0].rstrip(".")
    if len(first) > 100:
        first = first[:100].rsplit(" ", 1)[0].rstrip(",;:(") + " ..."
    return first[:1].upper() + first[1:]


def section(cmd: str, p) -> list:
    lines = [f"## emir {cmd}", ""]
    lines += description(p.description)
    lines += ["```text", synopsis(cmd, p), "```", ""]
    for g in p._action_groups:
        acts = [a for a in g._group_actions
                if a.help is not argparse.SUPPRESS and not isinstance(a, argparse._HelpAction)]
        if not acts:
            continue
        title = GROUP_TITLES.get(g.title, g.title)
        lines += [f"**{escape(title[0].upper() + title[1:])}**", ""]
        lines += [item(a, p.prog) for a in acts]
        lines.append("")
    return lines


def render() -> str:
    sys.path.insert(0, ROOT)
    from emir import cli
    from emir.mcp_tools import capture_parser
    # a command with sub-commands (`emir process new`) gets a section per
    # sub-command after its own
    cmds = []
    for c in sorted(cli.COMMANDS):
        cmds += [c] + [f"{c} {sub}" for sub in cli.SUBCOMMANDS.get(c, ())]
    lines = [HEADER.rstrip("\n"), "", "| command | what it does |", "|---|---|"]
    parsers = {}
    for c in cmds:
        p = capture_parser(c)
        if p is None:
            raise SystemExit(f"gen_cli_reference: no parser captured for `emir {c}`")
        parsers[c] = p
        lines.append(f"| [`emir {c}`](#emir-{c.replace(' ', '-')}) | "
                     f"{escape(summary_line(c, p))} |")
    lines.append("")
    for c in cmds:
        lines += section(c, parsers[c])
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="gen_cli_reference", allow_abbrev=False,
                                 description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 when the page is stale")
    a = ap.parse_args(argv)
    text = render()
    old = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else None
    rel = os.path.relpath(OUT, ROOT)
    if a.check:
        if old != text:
            print(f"{rel} is stale: run python scripts/gen_cli_reference.py", file=sys.stderr)
            return 1
        print(f"{rel} is up to date")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
