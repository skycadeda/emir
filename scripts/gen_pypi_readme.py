#!/usr/bin/env python3
"""Write README.pypi.md, the package's long description, from README.md.

README.md links its pages and images relative to the repository
(`docs/getting-started.md`, `docs/images/hero.png`): right on GitHub, broken
on PyPI and in `pip show -v`, which have no repository around the text. The
long description is README.md with every such link made absolute:

* a page or a directory -> `<REPO_URL>/blob/main/<path>` (`/tree/main/` for
  a directory), its `#anchor` kept;
* an image (`![..](..)`, `src=`, `srcset=`) -> the raw file,
  `https://raw.githubusercontent.com/<owner>/<repo>/main/<path>`.

A `<picture>` with a light-scheme `<source>` becomes its `<img>` showing that
source: PyPI strips `<source>` and shows its pages light, so the `<img>`'s
own (dark) image would stand on a white page.

Links that are already absolute (`https:`, `mailto:`) and in-page anchors
(`#...`) stay as they are. README.md is the single source; never edit the
generated file by hand.

    python scripts/gen_pypi_readme.py            # write it
    python scripts/gen_pypi_readme.py --check    # exit 1 if it is stale

`pyproject.toml` names it (`readme`); `tests/test_packaging.py` runs the
check and fails on any relative link left in it.
"""
from __future__ import annotations

import argparse
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC = os.path.join(ROOT, "README.md")
OUT = os.path.join(ROOT, "README.pypi.md")
sys.path.insert(0, ROOT)

from emir.repo import BRANCH, REPO_URL  # noqa: E402

HEADER = ("<!-- GENERATED by scripts/gen_pypi_readme.py from README.md: the long description "
          "PyPI shows, with every repository link absolute. Do not edit by hand. -->\n\n")
IMAGE_EXT = (".png", ".svg", ".jpg", ".jpeg", ".gif", ".webp", ".pdf")
#: a Markdown link or image: `[text](target)` / `![alt](target)`
MD_LINK = re.compile(r"(!?)\[((?:[^\[\]]|\[[^\]]*\])*)\]\(([^)\s]+)\)")
#: an HTML attribute holding a URL
HTML_ATTR = re.compile(r'\b(src|srcset|href)="([^"]+)"')
#: a <picture> whose light-scheme <source> PyPI would drop
PICTURE = re.compile(r'<picture>\s*<source media="\(prefers-color-scheme: light\)" '
                     r'srcset="([^"]+)">\s*(<img\b[^>]*?\bsrc=")[^"]+("[^>]*>)\s*</picture>')


def _raw_base() -> str:
    owner_repo = REPO_URL.split("github.com/", 1)[1].rstrip("/")
    return f"https://raw.githubusercontent.com/{owner_repo}/{BRANCH}/"


def absolute(target: str, image: bool = False) -> str:
    """The absolute URL of a link `target` written relative to the
    repository root ("" or an absolute target: unchanged)."""
    if re.match(r"^[a-z][a-z0-9+.-]*:", target, re.I) or target.startswith(("#", "/")):
        return target
    path, hash_, anchor = target.partition("#")
    path = path[2:] if path.startswith("./") else path
    if image or path.lower().endswith(IMAGE_EXT):
        return _raw_base() + path
    kind = "tree" if (path.endswith("/") or not path) else "blob"
    return f"{REPO_URL}/{kind}/{BRANCH}/{path}" + (hash_ + anchor if hash_ else "")


def render(text: str) -> str:
    """README.md with every relative link absolute (the module doc)."""
    def md(m):
        bang, label, target = m.groups()
        return f"{bang}[{label}]({absolute(target, image=bool(bang))})"

    def html(m):
        attr, target = m.groups()
        return f'{attr}="{absolute(target, image=attr != "href")}"'
    text = PICTURE.sub(lambda m: m.group(2) + m.group(1) + m.group(3), text)
    return HEADER + HTML_ATTR.sub(html, MD_LINK.sub(md, text))


def relative_links(text: str) -> list:
    """The relative link targets left in `text` (none, in the generated file)."""
    out = [t for _b, _l, t in MD_LINK.findall(text)]
    out += [t for _a, t in HTML_ATTR.findall(text)]
    return [t for t in out if absolute(t) != t]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0], allow_abbrev=False)
    ap.add_argument("--check", action="store_true", help="exit 1 if README.pypi.md is stale")
    a = ap.parse_args(argv)
    with open(SRC, encoding="utf-8") as f:
        want = render(f.read())
    if a.check:
        try:
            with open(OUT, encoding="utf-8") as f:
                have = f.read()
        except OSError:
            have = None
        if have != want:
            print("README.pypi.md is stale: run python scripts/gen_pypi_readme.py",
                  file=sys.stderr)
            return 1
        print("README.pypi.md is current")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(want)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
